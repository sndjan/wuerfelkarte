/**
 * Downloads the Noto emoji the app uses into `public/emoji/` and writes the
 * manifest `src/components/emoji/manifest.ts`.
 *
 *   npm run emoji          # after adding an emoji anywhere under src/
 *
 * Every emoji found in `src/` gets the static Noto Color Emoji SVG
 * (`<key>.svg`, Apache License 2.0) and, where Google drew one, the animated
 * Noto emoji as Lottie (`<key>.json`, CC BY 4.0). The files are committed, so
 * the app never loads anything from Google at runtime. Credits:
 * `src/app/lizenzen/page.tsx` and `public/emoji/LICENSE.md`.
 *
 * Behind a proxy, run with NODE_USE_ENV_PROXY=1 (Node 22.21+).
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "public/emoji");
const MANIFEST = path.join(ROOT, "src/components/emoji/manifest.ts");
const BASE = "https://fonts.gstatic.com/s/e/notoemoji/latest";

/** Emoji that are always available, even when no source file names them. */
const EXTRA = [];

const pictographic = /\p{Extended_Pictographic}|\p{Regional_Indicator}|⃣/u;
const segmenter = new Intl.Segmenter("en", { granularity: "grapheme" });

function scan(dir, found) {
  for (const name of fs.readdirSync(dir)) {
    const file = path.join(dir, name);
    if (fs.statSync(file).isDirectory()) scan(file, found);
    else if (/\.(ts|tsx)$/.test(name) && !/\.test\.|fixtures|manifest\.ts$/.test(name)) {
      for (const { segment } of segmenter.segment(fs.readFileSync(file, "utf8"))) {
        // Plain symbols like ✓ ← ⋮ stay text; an emoji has an emoji code point or VS16.
        if (pictographic.test(segment) && /\p{Emoji_Presentation}|️|⃣/u.test(segment)) found.add(segment);
      }
    }
  }
  return found;
}

/** "🧙‍♂️" → "1f9d9_200d_2642": the file name, without variation selectors. */
const keyOf = (emoji) =>
  [...emoji]
    .filter((c) => c !== "️")
    .map((c) => c.codePointAt(0).toString(16))
    .join("_");

/** The spellings Google's server might use for one emoji. */
function candidates(emoji) {
  const hex = [...emoji].map((c) => c.codePointAt(0).toString(16));
  const pad = (list) => list.map((h) => h.padStart(4, "0")).join("_");
  const without = hex.filter((h) => h !== "fe0f");
  return [...new Set([without.join("_"), hex.join("_"), pad(without), pad(hex)])];
}

async function download(emoji, file) {
  for (const code of candidates(emoji)) {
    const res = await fetch(`${BASE}/${code}/${file}`);
    if (res.ok) return Buffer.from(await res.arrayBuffer());
  }
  return null;
}

const emojis = [...scan(path.join(ROOT, "src"), new Set(EXTRA))].sort();
fs.mkdirSync(OUT, { recursive: true });

const entries = {};
const missing = [];
await Promise.all(
  emojis.map(async (emoji) => {
    const key = keyOf(emoji);
    if (entries[emoji.replaceAll("️", "")]) return;
    const svgPath = path.join(OUT, `${key}.svg`);
    const jsonPath = path.join(OUT, `${key}.json`);
    if (!fs.existsSync(svgPath)) {
      const svg = await download(emoji, "emoji.svg");
      if (!svg) return missing.push(emoji);
      fs.writeFileSync(svgPath, svg);
    }
    if (!fs.existsSync(jsonPath)) {
      const json = await download(emoji, "lottie.json");
      if (json) fs.writeFileSync(jsonPath, JSON.stringify(JSON.parse(json.toString("utf8"))));
    }
    entries[emoji.replaceAll("️", "")] = { k: key, a: fs.existsSync(jsonPath) ? 1 : 0 };
  }),
);

const sorted = Object.keys(entries).sort();
fs.writeFileSync(
  MANIFEST,
  `// Generated by scripts/fetch-noto-emoji.mjs — do not edit by hand.
// Key: the emoji without variation selectors. k: file name in public/emoji/,
// a: 1 when an animated Noto emoji (<k>.json) exists, else only <k>.svg.
export const NOTO_EMOJI: Record<string, { k: string; a: 0 | 1 }> = {
${sorted.map((e) => `  ${JSON.stringify(e)}: { k: ${JSON.stringify(entries[e].k)}, a: ${entries[e].a} },`).join("\n")}
};
`,
);

const animated = sorted.filter((e) => entries[e].a).length;
console.log(`${sorted.length} emoji, ${animated} animated.`);
if (missing.length) console.log(`Not in Noto (stay text): ${missing.join(" ")}`);
